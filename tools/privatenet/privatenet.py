#!/usr/bin/env python3
"""Private networking per tenant over WireGuard (plan item 32).

Each tenant gets its own /29 from 10.200.0.0/16 (tunnel address space)
and its own WireGuard interface on the cache gateway. The gateway only
accepts traffic from the tenant's peers and forwards it to that tenant's
database. Keys are generated by `wg genkey` on each side; this module only
handles public keys and never sees a private key (configs use PostUp
`wg set ... private-key <file>`).
"""
import base64
import ipaddress

POOL = ipaddress.ip_network("10.200.0.0/16")


def _pubkey(k):
    try:
        ok = len(base64.b64decode(k, validate=True)) == 32
    except Exception:
        ok = False
    if not ok:
        raise ValueError("not a WireGuard public key")
    return k


def allocate(index):
    """Tenant index -> its /29 (gateway gets .1, peers .2-.6)."""
    subnets = POOL.subnets(new_prefix=29)
    for i, s in enumerate(subnets):
        if i == index:
            return s
    raise ValueError("pool exhausted")


def gateway_conf(index, listen_port, peers, db_addr, db_port=6379):
    net = allocate(index)
    hosts = list(net.hosts())
    if len(peers) > len(hosts) - 1:
        raise ValueError("too many peers for one tenant subnet")
    iface = "wgt%d" % index
    lines = ["[Interface]", "Address = %s/29" % hosts[0], "ListenPort = %d" % listen_port,
             "PostUp = wg set %%i private-key /etc/wireguard/%s.key" % iface,
             # only this tenant's tunnel may reach this tenant's DB port
             "PostUp = iptables -A FORWARD -i %%i -d %s -p tcp --dport %d -j ACCEPT" % (db_addr, db_port),
             "PostUp = iptables -A FORWARD -i %i -j DROP",
             "PostDown = iptables -D FORWARD -i %%i -d %s -p tcp --dport %d -j ACCEPT" % (db_addr, db_port),
             "PostDown = iptables -D FORWARD -i %i -j DROP"]
    for i, pk in enumerate(peers):
        lines += ["", "[Peer]", "PublicKey = %s" % _pubkey(pk), "AllowedIPs = %s/32" % hosts[i + 1]]
    return iface, "\n".join(lines) + "\n"


def client_conf(index, peer_no, gateway_pub, endpoint, db_addr):
    hosts = list(allocate(index).hosts())
    return "\n".join(["[Interface]", "Address = %s/32" % hosts[peer_no + 1],
                      "PostUp = wg set %i private-key /etc/wireguard/cmo.key", "",
                      "[Peer]", "PublicKey = %s" % _pubkey(gateway_pub), "Endpoint = %s" % endpoint,
                      "AllowedIPs = %s/32" % db_addr, "PersistentKeepalive = 25"]) + "\n"
