#!/usr/bin/env python3
"""Config presets (plan items 22 multi-core, 48 cache mode, 73 strong consistency, 77 RDMA).

  python3 presets.py cache strong --cores 8 > /etc/cache-me-outside/presets.conf
then add `include /etc/cache-me-outside/presets.conf` to valkey.conf.

  io       io-threads from core count (Valkey 8 I/O threads); confirm with deploy/bench.sh
  cache    pure-cache: no persistence, allkeys-lfu eviction, lazy freeing
  strong   writes refused unless N replicas are connected and recent; pair with
           WAIT/WAITAOF in clients for per-write acks
  rdma     RDMA listener (experimental; image must be built with BUILD_RDMA=module)
Conflicting presets (cache + strong) are refused: a cache that drops writes on
memory pressure can't promise durable acknowledged writes.
"""
import argparse
import sys


def io(cores):
    if cores < 1:
        raise ValueError("cores must be >= 1")
    # Leave one core for the main thread; cap at 8 where Valkey's gains flatten.
    n = max(1, min(8, cores - 1))
    return ["io-threads %d" % n]


def cache():
    return ["appendonly no", 'save ""', "maxmemory-policy allkeys-lfu", "lfu-log-factor 10",
            "lfu-decay-time 1", "lazyfree-lazy-eviction yes", "lazyfree-lazy-expire yes",
            "activedefrag yes"]


def strong(replicas=1, max_lag=5):
    if replicas < 1:
        raise ValueError("strong mode needs at least 1 replica")
    return ["appendonly yes", "appendfsync always", "min-replicas-to-write %d" % replicas,
            "min-replicas-max-lag %d" % max_lag, "maxmemory-policy noeviction",
            "repl-diskless-sync yes"]


def rdma(port=6379, bind="0.0.0.0"):
    return ["loadmodule /usr/local/lib/valkey-rdma.so", "rdma-port %d" % port, "rdma-bind %s" % bind]


def render(names, cores=0, replicas=1, max_lag=5, rdma_port=6379):
    if "cache" in names and "strong" in names:
        raise ValueError("cache and strong presets conflict")
    out = ["# Generated by tools/presets/presets.py: " + " ".join(names)]
    for n in names:
        if n == "io":
            out += io(cores)
        elif n == "cache":
            out += cache()
        elif n == "strong":
            out += strong(replicas, max_lag)
        elif n == "rdma":
            out += rdma(rdma_port)
        else:
            raise ValueError("unknown preset %r" % n)
    keys = [l.split()[0] for l in out[1:]]
    dup = {k for k in keys if keys.count(k) > 1}
    if dup:
        raise ValueError("presets set the same directive twice: %s" % ", ".join(sorted(dup)))
    return "\n".join(out) + "\n"


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("presets", nargs="+")
    ap.add_argument("--cores", type=int, default=0)
    ap.add_argument("--replicas", type=int, default=1)
    ap.add_argument("--max-lag", type=int, default=5)
    a = ap.parse_args(argv)
    if "io" in a.presets and not a.cores:
        import os
        a.cores = os.cpu_count() or 1
    sys.stdout.write(render(a.presets, a.cores, a.replicas, a.max_lag))


if __name__ == "__main__":
    main()
